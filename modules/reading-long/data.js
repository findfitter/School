// Длинные предложения (5–6 слов). Строятся кодом из предложений модуля «Собери предложение»
// (../reading-sentences/data.js), чтобы не дублировать героев, действия и места:
//   two  — «Кот пьёт молоко и спит»                       (5 слов: действие с предметом + второе действие)
//   adj  — «Весёлый кот спит на мягком диване»            (6 слов: прилагательные у героя и у места)
//   pair — «Кот и собака спят на траве»                   (6 слов: двое героев, действие и место)
// Лишние слова для верхнего уровня не подходят по смыслу или по форме (не тот род, число, падеж)
// или спорят с картинкой, поэтому второго верного ответа у них нет.

import { SENTENCES as BASE } from '../reading-sentences/data.js';

const acts = BASE.filter((s) => s.kind === 'act'); // [кто, глагол, что], scene: [кто, что]
const places = BASE.filter((s) => s.kind === 'place'); // [кто, глагол, предлог, где], scene: [кто, где]

// Род героя: нужен, чтобы прилагательное согласовалось («большой кот», «большая собака»).
const GENDER = {
  Кот: 'm', Собака: 'f', Мышь: 'f', Заяц: 'm', Корова: 'f', Лошадь: 'f', Медведь: 'm', Лиса: 'f', Слон: 'm',
  Птица: 'f', Утка: 'f', Рыба: 'f', Сова: 'f', Мальчик: 'm', Девочка: 'f', Мама: 'f', Папа: 'm', Бабушка: 'f',
  Дедушка: 'm', Волк: 'm', Лев: 'm', Обезьяна: 'f', Панда: 'f', Пингвин: 'm', Кит: 'm', Дельфин: 'm', Лебедь: 'm',
  Орёл: 'm', Бабочка: 'f', Пчела: 'f', Крокодил: 'm', Ёжик: 'm',
};

// Прилагательные для героев (мужской и женский род) — не про цвет, чтобы не спорить с картинкой.
const HERO_ADJ = [
  ['большой', 'большая'], ['маленький', 'маленькая'], ['добрый', 'добрая'],
  ['весёлый', 'весёлая'], ['умный', 'умная'], ['смелый', 'смелая'],
];

const ADULTS = ['Мама', 'Папа', 'Бабушка', 'Дедушка'];

// Прилагательное к месту: [верная форма после предлога, неверная — «именительная» — для лишней фишки].
const PLACE_ADJ = {
  'на диване': ['мягком', 'мягкий'],
  'на дереве': ['высоком', 'высокое'],
  'по траве': ['зелёной', 'зелёная'],
  'на траве': ['зелёной', 'зелёная'],
  'под деревом': ['высоким', 'высокое'],
  'в доме': ['тёплом', 'тёплый'],
  'по лесу': ['тёмному', 'тёмный'],
  'в лесу': ['тёмном', 'тёмный'],
  'в небе': ['синем', 'синее'],
  'в воде': ['чистой', 'чистая'],
  'в море': ['синем', 'синее'],
  'по снегу': ['белому', 'белый'],
  'на горе': ['высокой', 'высокая'],
  'на цветке': ['красивом', 'красивый'],
  'по парку': ['большому', 'большой'],
  'в саду': ['зелёном', 'зелёный'],
};

// Второе действие героя («… и спит»): глагол, картинка. Выбирается по тому, что герой умеет.
const SECOND = {
  земля: [['спит', '💤'], ['бежит', '🏃']],
  птица: [['летит', '☁️'], ['поёт', '🎵']],
  вода: [['плывёт', '🌊']],
  человек: [['спит', '💤'], ['поёт', '🎵'], ['бежит', '🏃']],
};
const KIND_OF = {
  Кот: 'земля', Собака: 'земля', Мышь: 'земля', Заяц: 'земля', Корова: 'земля', Лошадь: 'земля', Медведь: 'земля',
  Лиса: 'земля', Слон: 'земля', Волк: 'земля', Лев: 'земля', Обезьяна: 'земля', Панда: 'земля', Ёжик: 'земля',
  Птица: 'птица', Сова: 'птица', Орёл: 'птица', Утка: 'птица', Лебедь: 'птица', Пингвин: 'вода', Дельфин: 'вода',
  Крокодил: 'вода', Мальчик: 'человек', Девочка: 'человек', Мама: 'человек', Папа: 'человек', Бабушка: 'человек',
  Дедушка: 'человек',
};
const ALL_SECOND = ['спит', 'бежит', 'летит', 'поёт', 'плывёт'];

// Двое героев и общее место: [глагол во мн. числе, глагол в ед. числе (лишнее слово), предлог, место, картинка]
const PAIR_PLACES = [
  ['бегут', 'бежит', 'по', 'траве', '🌿'],
  ['сидят', 'сидит', 'на', 'траве', '🌿'],
  ['идут', 'идёт', 'по', 'лесу', '🌲'],
  ['спят', 'спит', 'в', 'лесу', '🌲'],
  ['спят', 'спит', 'в', 'доме', '🏠'],
  ['сидят', 'сидит', 'на', 'диване', '🛋️'],
];
const HOME_PLACES = ['в доме', 'на диване'];
const PAIR_HEROES = ['Кот', 'Собака', 'Заяц', 'Лиса', 'Медведь', 'Лошадь', 'Волк', 'Мальчик', 'Девочка', 'Панда', 'Лев', 'Обезьяна'];
const HOME_HEROES = ['Кот', 'Собака', 'Мальчик', 'Девочка'];

function build() {
  const sentences = [];
  const add = (kind, words, scene, extras) => sentences.push({ key: words.join(' '), kind, words, scene, extras });
  const emojiOf = new Map(BASE.map((s) => [s.words[0], s.scene[0]]));

  // two: «Кот пьёт молоко и спит»; второе действие не должно повторять первый глагол
  for (const s of acts) {
    const [who, verb, what] = s.words;
    for (const [second, emoji] of SECOND[KIND_OF[who]] || []) {
      if (second === verb) continue;
      add('two', [who, verb, what, 'и', second], [...s.scene, emoji],
        ALL_SECOND.filter((w) => w !== second));
    }
  }

  // adj: «Весёлый кот спит на мягком диване»; два варианта прилагательных на каждое предложение
  places.forEach((s, index) => {
    const [who, verb, prep, where] = s.words;
    const placeAdj = PLACE_ADJ[`${prep} ${where}`];
    const gender = GENDER[who];
    if (!placeAdj || !gender) return;
    // «маленький папа» звучит странно, «большой … по большому парку» — повтор слова
    const options = HERO_ADJ.filter(([m]) => !(ADULTS.includes(who) && m === 'маленький') && !(m === 'большой' && placeAdj[0].startsWith('больш')));
    for (let k = 0; k < 2; k++) {
      const pair = options[(index + k * 3) % options.length];
      const hero = gender === 'm' ? pair[0] : pair[1];
      const wrongHero = gender === 'm' ? pair[1] : pair[0]; // не тот род
      const first = hero[0].toUpperCase() + hero.slice(1);
      add('adj', [first, who.toLowerCase(), verb, prep, placeAdj[0], where], s.scene, [wrongHero, placeAdj[1]]);
    }
  });

  // pair: «Кот и собака спят на траве»
  for (let i = 0; i < PAIR_HEROES.length; i++) {
    for (let j = i + 1; j < PAIR_HEROES.length; j++) {
      const first = PAIR_HEROES[i];
      const second = PAIR_HEROES[j];
      for (const [plural, single, prep, where, emoji] of PAIR_PLACES) {
        if (HOME_PLACES.includes(`${prep} ${where}`) && !(HOME_HEROES.includes(first) && HOME_HEROES.includes(second))) continue;
        add('pair', [first, 'и', second.toLowerCase(), plural, prep, where],
          [emojiOf.get(first), emojiOf.get(second), emoji], [single]);
      }
    }
  }
  return sentences;
}

export const SENTENCES = build();
