function build() {
  const sentences = [];
  const add = (kind, words, scene, extras) => sentences.push({ key: words.join(' '), kind, words, scene, extras });

  // Лишние слова для верхнего уровня берутся только из того, что показано на картинке
  // (кто, что, где), поэтому они точно не подходят и не дают второго верного предложения.
  const subjectNames = SUBJECTS.map((s) => s.w);
  const allObjects = [...new Set(SUBJECTS.flatMap((s) => s.act.map((a) => a[1])))];
  const allPlaces = [...new Set(SUBJECTS.flatMap((s) => s.place.map((p) => p[2])))];

  for (const s of SUBJECTS) {
    for (const [verb, obj, emoji] of s.act) {
      add('act', [s.w, verb, obj], [s.e, emoji], [...subjectNames, ...allObjects]);
    }
    for (const [verb, prep, place, emoji] of s.place) {
      add('place', [s.w, verb, prep, place], [s.e, emoji], [...subjectNames, ...allPlaces]);
    }
  }

  const emojiOf = new Map(SUBJECTS.map((s) => [s.w, s.e]));
  const seenPair = new Set();
  const addPair = (first, second, verb, emoji, extras) => {
    const key = `${first}|${second}|${verb}`;
    if (seenPair.has(key) || first === second) return;
    seenPair.add(key);
    add('plural', [first, 'и', second.toLowerCase(), verb], [emojiOf.get(first), emojiOf.get(second), emoji], extras);
  };
  for (const group of PAIR_GROUPS) {
    const n = group.heroes.length;
    group.heroes.forEach((first, i) => {
      for (let k = 0; k < group.per; k++) {
        const second = group.heroes[(i + 1 + k * 4) % n]; // шаг 4: рядом стоящие не склеиваются в одни и те же пары
        const [verb, emoji] = group.verbs[(i + k * 3) % group.verbs.length];
        addPair(first, second, verb, emoji, group.extras);
      }
    });
  }
  FRIEND_PAIRS.forEach(([first, second], i) => {
    for (let k = 0; k < 2; k++) {
      const [verb, emoji] = FRIEND_VERBS[(i + k * 2) % FRIEND_VERBS.length];
      addPair(first, second, verb, emoji, ['летят', 'плывут', 'поют']);
    }
  });

  // free: без картинки (scene пустая, nopic: true) и без лишних фишек
  for (const text of FREE) {
    const words = text.split(' ');
    sentences.push({ key: text, kind: 'free', words, scene: [], extras: [], nopic: true });
  }
  return sentences;
}

export const SENTENCES = build();

