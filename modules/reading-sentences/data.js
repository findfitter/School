const parseAct = (text) => {
  const [verb, object] = text.split(' ');
  const emoji = OBJECTS.get(object);
  if (!emoji) throw new Error(`reading-sentences: нет картинки предмета «${object}» (OBJECTS)`);
  return [verb, object, emoji];
};
const parsePlace = (text) => {
  const [verb, prep, place] = text.split(' ');
  const info = PLACES[`${prep} ${place}`];
  if (!info) throw new Error(`reading-sentences: нет места «${prep} ${place}» (PLACES)`);
  return [verb, prep, place, info[0]];
};

