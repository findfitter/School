function render(c) {
  switch (c.cat) {
    case 'ab': {
      const S = nom(c.animal);
      const [v3, inf] = need(VERB, c.verb, 'умение');
      return {
        pos: [P(sent(`${S} ${v3}`)), P(sent(`${S} умеет ${inf}`))],
        neg: [N(sent(`${S} не ${v3}`)), N(sent(`${S} не умеет ${inf}`))],
      };
    }
    case 'sd': {
      const S = nom(c.animal);
      const sound = need(SOUND, c.sound, 'звук');
      return { pos: [P(sent(`${S} ${sound}`))], neg: [N(sent(`${S} не ${sound}`))] };
    }
    case 'has': {
      const G = gen(c.animal);
      const [has, no] = PART_OVERRIDE[`${c.animal}:${c.part}`] || need(PART, c.part, 'часть тела');
      return {
        pos: [P(sent(`У ${G} есть ${has}`)), P(sent(`${has} есть у ${G}`))],
        neg: [N(sent(`У ${G} нет ${no}`)), N(sent(`${no} нет у ${G}`))],
      };
    }
    case 'home': {
      const S = nom(c.animal);
      const place = need(PLACE, c.place, 'место');
      return {
        pos: [P(sent(`${S} живёт ${place}`)), P(sent(`${place} живёт ${S}`))],
        neg: [N(sent(`${S} не живёт ${place}`)), N(sent(`${place} не живёт ${S}`))],
      };
    }
    case 'eat': {
      const S = nom(c.animal);
      const [acc, instr] = need(FOOD, c.food, 'еда');
      return {
        pos: [P(sent(`${S} ест ${acc}`)), P(sent(`${S} питается ${instr}`))],
        neg: [N(sent(`${S} не ест ${acc}`)), N(sent(`${S} не питается ${instr}`))],
      };
    }
    case 'prop': {
      const item = need(NOUN, c.item, 'предмет');
      const adj = need(ADJ, c.prop, 'свойство')[need(GENDER, item.g, 'род')];
      return { pos: [P(sent(`${item.nom} ${adj}`))], neg: [N(sent(`${item.nom} не ${adj}`))] };
    }
    case 'use': {
      const tool = need(TOOL, c.tool, 'инструмент');
      const [pos, neg] = need(ACT, c.act, 'действие');
      return { pos: [P(sent(`${tool} ${pos}`))], neg: [N(sent(`${tool} ${neg}`))] };
    }
    case 'job': {
      const S = nom(c.animal);
      const [pos, neg] = need(DEED, c.deed, 'дело');
      return { pos: [P(sent(`${S} ${pos}`))], neg: [N(sent(`${S} ${neg}`))] };
    }
    case 'cmp': {
      const [more, less] = need(CMP, c.dim, 'сравнение');
      const A = nom(c.hi);
      const B = nom(c.lo);
      return {
        pos: [P(sent(`${A} ${more} ${gen(c.lo)}`)), P(sent(`${B} ${less} ${gen(c.hi)}`))],
        neg: [P(sent(`${B} ${more} ${gen(c.hi)}`)), P(sent(`${A} ${less} ${gen(c.lo)}`))],
      };
    }
    case 'num': {
      if (c.kind === 'cmp') {
        return {
          pos: [P(sent(`${NUM[c.a]} больше ${NUM_GEN[c.b]}`)), P(sent(`${NUM[c.b]} меньше ${NUM_GEN[c.a]}`))],
          neg: [P(sent(`${NUM[c.b]} больше ${NUM_GEN[c.a]}`)), P(sent(`${NUM[c.a]} меньше ${NUM_GEN[c.b]}`))],
        };
      }
      const op = c.kind === 'sum' ? 'плюс' : 'минус';
      const line = (x) => [P(sent(`${NUM[c.a]} ${op} ${NUM[c.b]} — ${NUM[x]}`)), P(sent(`${NUM[c.a]} ${op} ${NUM[c.b]} будет ${NUM[x]}`))];
      return { pos: line(c.c), neg: c.alts.flatMap(line) };
    }
    case 'cnt': {
      const [lead, forms, g] = need(COUNT, c.what, 'счёт');
      const line = (n) => P(sent(`${lead} ${counted(n, forms, g)}`));
      return { pos: [line(c.n)], neg: c.alts.map(line) };
    }
    case 'time': {
      if (c.kind === 'order') {
        const set = ORDER[c.set];
        const x = need(set, c.x, 'порядок');
        const y = need(set, c.y, 'порядок');
        const pos = [P(sent(`После ${x[1]} идёт ${y[0]}`)), P(sent(`Перед ${y[2]} идёт ${x[0]}`))];
        const neg = c.alts.flatMap((z) => {
          const Z = need(set, z, 'порядок');
          return [P(sent(`После ${x[1]} идёт ${Z[0]}`)), P(sent(`Перед ${Z[2]} идёт ${x[0]}`))];
        });
        return { pos, neg };
      }
      if (c.kind === 'sfeat') {
        const [pos, neg] = need(SFEAT, c.feat, 'сезон');
        return { pos: [P(sent(`${need(SEASON_IN, c.season, 'время года')} ${pos}`))], neg: [N(sent(`${SEASON_IN[c.season]} ${neg}`))] };
      }
      const [pos, neg] = need(DFEAT, c.feat, 'время суток');
      return { pos: [P(sent(`${need(PART_IN, c.part, 'время суток')} ${pos}`))], neg: [N(sent(`${PART_IN[c.part]} ${neg}`))] };
    }
    default:
      throw new Error(`Неизвестный вид утверждения: ${c.cat}`);
  }
}

export const BANK = buildBank({ render });
