const seen = new Set();

export const WORDS = PAIRS.split(/[\n|]/)
  .map((item) => item.trim())
  .filter(Boolean)
  .map((item) => {
    const [word, emoji] = item.split(/\s+/);
    return { word, emoji };
  })
  // Одинаковые слова или картинки не нужны — иначе ответ будет неоднозначным.
