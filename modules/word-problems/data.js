// Число и предмет в правильной форме: «3 яблока», «5 яблок».
export function counted(n, noun) {
  const last = n % 10;
  const tens = n % 100;
  const form = last === 1 && tens !== 11 ? 0 : last >= 2 && last <= 4 && (tens < 12 || tens > 14) ? 1 : 2;
  return `${n} ${noun[form]}`;
}
