// «Аглая и гусь Гордей» — сценарий комикса (данные). Тексты истории только здесь.
// Читаемый вид и проверки: node tools/comic-print.mjs [--check] [--assets]
//
// Панель:   p(bg, cast, bubbles, fx, task, props, splash)
//   bg      id фона (BACKGROUNDS); splash — id большого кадра (SPLASHES), он заменяет фон и героев картинкой
//   cast    [{ who, pose, at }] — at: 'l' | 'c' | 'r'; герои смотрят к центру, зеркалит движок
//   bubbles say (говорит) / shout (крик) / think (мысль) / whisper (шёпот) / box (рассказчик); «___» — пропуск для fill
//   fx      строки 'speed' | 'shake' | 'zoom' | 'flash' | 'feathers' | 'stars' | 'dots' | 'rain' | 'zzz' | 'exclaim:<кто>' | 'question:<кто>'
//           и sfx('ГА!', at, size) — звук-слово
//   task    одно задание на чтение (или null), типы ниже
//   props   [[id предмета, at]]
//
// Задания (правильный ответ всегда берётся из самой истории, в данных хранятся только неверные):
//   who(bubble, decoys)             кто это сказал (правильный — who облачка; decoys — id героев)
//   pick(bubble, decoys)            выбери фразу, которая подходит в облачко (правильная — текст облачка)
//   fill(bubble, word, decoys)      вставь слово вместо «___» в облачке
//   ask(question, right, decoys)    вопрос по прочитанному, три ответа (правильный — right)
//   tf(text, truth, fix)            правда или нет; у неверного утверждения fix — «как правильно»
//   next(ask, right, decoys)        что будет дальше (подтверждается следующим кадром)
//   order(lines)                    расставь предложения по порядку (в данных — верный порядок)

const A = 'ag';   // Аглая
const G = 'gor';  // Гордей
const Q = 'frog'; // лягушка Квак

const c = (who, pose, at) => ({ who, pose, at });
const say = (who, text) => ({ who, kind: 'say', text });
const shout = (who, text) => ({ who, kind: 'shout', text });
const think = (who, text) => ({ who, kind: 'think', text });
const whisper = (who, text) => ({ who, kind: 'whisper', text });
const box = (text) => ({ kind: 'box', text });
const sfx = (text, at = 'c', size = 'l', y = null) => ({ sfx: text, at, size, y }); // y — % сверху, только у больших кадров-картинок

const ask = (question, right, decoys) => ({ type: 'ask', ask: question, right, decoys });
const tf = (text, truth, fix = null) => ({ type: 'tf', text, truth, fix });
const who = (bubble, decoys) => ({ type: 'who', bubble, decoys });
const pick = (bubble, decoys) => ({ type: 'pick', bubble, decoys });
const fill = (bubble, word, decoys) => ({ type: 'fill', bubble, word, decoys });
const next = (ask, right, decoys) => ({ type: 'next', ask, right, decoys });
const order = (lines) => ({ type: 'order', lines });

const p = (bg, cast, bubbles, fx = [], task = null, props = [], splash = null) =>
  ({ bg, cast, bubbles, fx, task, props, splash });
const page = (...panels) => ({ panels }); // 3 кадра — раскладка «A», 4 кадра — «B»

