function build() {
  const sentences = [];
  const seenScene = new Set();
  // Картинка одна на предложение: если такая уже есть, второе предложение с ней не добавляем (иначе ответ неоднозначен)
  const add = (kind, words, scene, extras) => {
    const sceneKey = `${kind}|${scene.join('')}`;
    if (seenScene.has(sceneKey)) return;
    seenScene.add(sceneKey);
    sentences.push({ key: words.join(' '), kind, words, scene, extras });
  };

  // two: «Кот лакает молоко и спит»; второе действие не должно повторять первый глагол.
  // На каждое предложение — одно второе действие (по очереди), чтобы «спит» и «бежит» не лезли в каждое.
  const twoLimit = limiter();
  scattered(acts).forEach((s, index) => {
    const [who, verb, what] = s.words;
    const options = (SECOND[HEROES[who]?.kind] || []).filter(([second]) => second !== verb);
    if (!options.length) return;
    const [second, emoji] = options[index % options.length];
    if (!twoLimit(`v:${verb}`, 24) || !twoLimit(`o:${what}`, 14) || !twoLimit(`w:${who}`, 8)) return;
    add('two', [who, verb, what, 'и', second], [...s.scene, emoji], ALL_SECOND.filter((w) => w !== second));
  });

  // adj: «Весёлый кот спит на мягком диване»; прилагательное героя меняется по кругу
  const adjLimit = limiter();
  scattered(places).forEach((s, index) => {
    const [who, verb, prep, where] = s.words;
    const placeAdj = PLACE_ADJ[`${prep} ${where}`];
    const hero = HEROES[who];
    if (!placeAdj || !hero) return;
    if (!adjLimit(`v:${verb}`, 22) || !adjLimit(`p:${where}`, 12) || !adjLimit(`w:${who}`, 7)) return;
    // «маленький папа» звучит странно, «большой … по большому парку» — повтор слова
    const options = HERO_ADJ.filter(([m]) => !(ADULTS.includes(who) && m === 'маленький') && stem(m) !== stem(placeAdj[0]));
    const pair = options[index % options.length];
    const adj = hero.g === 'm' ? pair[0] : pair[1];
    const wrongHero = hero.g === 'm' ? pair[1] : pair[0]; // не тот род
    const first = adj[0].toUpperCase() + adj.slice(1);
    add('adj', [first, who.toLowerCase(), verb, prep, placeAdj[0], where], s.scene, [wrongHero, placeAdj[1]]);
  });

  // pair: «Кот и собака бегут по траве»; героев берём из подходящего списка, пары — вразброс, не «все со всеми»
  for (const [plural, single, prep, where, emoji, pool] of PAIR_PLACES) {
    const n = pool.length;
    for (let t = 0; t < Math.min(PAIRS_PER_PLACE, n * 2); t++) {
      const first = pool[(t * 3) % n];
      const second = pool[(t * 3 + 1 + (t % 2)) % n];
      if (first === second || !HEROES[first] || !HEROES[second]) continue;
      add('pair', [first, 'и', second.toLowerCase(), plural, prep, where], [HEROES[first].e, HEROES[second].e, emoji], [single]);
    }
  }

  // free: без картинки и без лишних фишек
  for (const text of FREE) {
    sentences.push({ key: text, kind: 'free', words: text.split(' '), scene: [], extras: [], nopic: true });
  }
  return sentences;
}

export const SENTENCES = build();
