// Кто может быть в предложении «X и Y …» и что они вместе делают.
const PAIR_SUBJECTS = ['Кот', 'Собака', 'Мышь', 'Заяц', 'Лошадь', 'Медведь', 'Лиса', 'Мальчик', 'Девочка'];
const PLURAL_VERBS = [['спят', '💤'], ['играют', '⚽'], ['бегут', '🏃']];

const PLURAL_EXTRA_VERBS = ['летят', 'плывут'];

function build() {
  const sentences = [];
  const add = (kind, words, scene, extras) => sentences.push({ key: words.join(' '), kind, words, scene, extras });

  // Лишние слова для верхнего уровня берутся только из того, что показано на картинке
  // (кто, что, где), поэтому они точно не подходят и не дают второго верного предложения.
  const subjectNames = SUBJECTS.map((s) => s.w);
  const allObjects = [...new Set(SUBJECTS.flatMap((s) => s.act.map((a) => a[1])))];
  const allPlaces = [...new Set(SUBJECTS.flatMap((s) => s.place.map((p) => p[2])))];

  for (const s of SUBJECTS) {
    for (const [verb, obj, emoji] of s.act) {
      add('act', [s.w, verb, obj], [s.e, emoji], [...subjectNames, ...allObjects]);
    }
    for (const [verb, prep, place, emoji] of s.place) {
      add('place', [s.w, verb, prep, place], [s.e, emoji], [...subjectNames, ...allPlaces]);
    }
  }
  const emojiOf = new Map(SUBJECTS.map((s) => [s.w, s.e]));
  for (const first of PAIR_SUBJECTS) {
    for (const second of PAIR_SUBJECTS) {
      if (first === second) continue;
      for (const [verb, emoji] of PLURAL_VERBS) {
        add('plural', [first, 'и', second.toLowerCase(), verb], [emojiOf.get(first), emojiOf.get(second), emoji],
          [...PLURAL_VERBS.map((v) => v[0]), ...PLURAL_EXTRA_VERBS]);
      }
    }
  }
  return sentences;
}

export const SENTENCES = build();
